export interface PaginationParams {
  page: number;
  limit: number;
}

export interface PaginatedResponse<T> {
  data: T[];
  pagination: {
    page: number;
    limit: number;
    total: number;
    totalPages: number;
  };
}

export interface ApiResponse<T> {
  success: boolean;
  data?: T;
  message?: string;
  error?: string;
}

export type Status = 'active' | 'inactive' | 'suspended' | 'pending';

export interface Timestamps {
  createdAt: Date;
  updatedAt: Date;
}
